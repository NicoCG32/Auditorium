import test from 'node:test'
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import {
  inspectHeader,
  validateSelection,
  validateAssociation,
  MAX_FILE_BYTES,
  MAX_TOTAL_BYTES,
  MAX_FILES,
} from './audio.mjs'

test('fixture manifests verify generated bytes, actual audio streams and short duration', async () => {
  const manifest = JSON.parse(
    await readFile(
      new URL('./fixtures/manifest.json', import.meta.url),
      'utf8',
    ),
  )
  assert.equal(manifest.files.length, 8)
  assert.equal(manifest.license, 'CC0-1.0')
  for (const row of manifest.files) {
    const bytes = await readFile(
      new URL(`./fixtures/${row.file}`, import.meta.url),
    )
    assert.equal(bytes.length, row.bytes)
    assert.equal(createHash('sha256').update(bytes).digest('hex'), row.sha256)
    assert.equal(row.streams.length, 1)
    assert.equal(row.streams[0].codec_type, 'audio')
    assert.ok(row.duration > 1 && row.duration < 1.5)
    assert.ok(inspectHeader(bytes.subarray(0, 128)).mime.startsWith('audio/'))
  }
})
test('signature validation is independent from filename/MIME and rejects fabricated media', () => {
  const wav = new Uint8Array(44)
  wav.set(new TextEncoder().encode('RIFF'), 0)
  wav.set(new TextEncoder().encode('WAVE'), 8)
  assert.equal(inspectHeader(wav).container, 'WAV')
  for (const value of [
    '',
    'a.mp3',
    '<script>alert(1)</script>',
    'Not actually RIFF WAVE',
  ])
    assert.throws(() => inspectHeader(new TextEncoder().encode(value)))
})
test('size and count budgets cover exact boundaries and replacements exclude the previous file', () => {
  assert.doesNotThrow(() => validateSelection({ size: MAX_FILE_BYTES }))
  assert.throws(() => validateSelection({ size: MAX_FILE_BYTES + 1 }))
  for (const size of [0, -1, NaN, Infinity, 1.5])
    assert.throws(() => validateSelection({ size }))
  const full = Array.from({ length: MAX_FILES }, (_, index) => ({
    id: String(index),
    file: { size: 1 },
  }))
  assert.throws(() => validateSelection({ size: 1 }, full))
  assert.doesNotThrow(() => validateSelection({ size: 1 }, full, '0'))
  const remaining = [
    { id: 'old', file: { size: MAX_TOTAL_BYTES - MAX_FILE_BYTES } },
  ]
  assert.doesNotThrow(() =>
    validateSelection({ size: MAX_FILE_BYTES }, remaining),
  )
  assert.throws(() =>
    validateSelection({ size: MAX_FILE_BYTES }, [
      { id: 'x', file: { size: MAX_TOTAL_BYTES - MAX_FILE_BYTES + 1 } },
    ]),
  )
})
test('personal association only admits a track in the same album and carries no acquisition/rating data', () => {
  assert.deepEqual(validateAssociation({ userAlbumId: 'entry-a' }), {
    userAlbumId: 'entry-a',
  })
  assert.deepEqual(
    validateAssociation({
      userAlbumId: 'entry-a',
      trackId: 'track-a',
      acquired: true,
      rating: 10,
    }),
    { userAlbumId: 'entry-a', trackId: 'track-a' },
  )
  assert.throws(() =>
    validateAssociation({ userAlbumId: 'entry-a', trackId: 'track-b' }),
  )
  assert.throws(() => validateAssociation({ userAlbumId: 'missing' }))
})
